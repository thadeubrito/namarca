import { and, eq } from "drizzle-orm";
import { db } from "@/db";
import { campaignAssets, campaignEditor, campaignPackages, campaigns } from "@/db/schema";
import { assertEditable, CampaignEditorError } from "./campaign-editor";
import { deletePrivateObject, listPrivateObjects } from "./storage";
import { assetIdFromKey, campaignAssetKey, campaignAssetPrefix, CLEANUP_BATCH_LIMIT, oldEnough, referencedAssetIds } from "./asset-cleanup-policy";

export type CleanupResult = { deleted: string[]; failed: string[]; skipped: string[]; deletedBytes: number };
// All reads and external deletes are serialized with upload/save by the campaign row.
export async function cleanupCampaignAssets(campaignId: string, options: { ids?: string[]; afterSave?: boolean } = {}) {
  if (options.ids && options.ids.length > CLEANUP_BATCH_LIMIT) throw new CampaignEditorError(422, "Máximo de 100 materiais por lote");
  return db.transaction(async (tx) => {
    const [campaign] = await tx.select().from(campaigns).where(eq(campaigns.id, campaignId)).for("update");
    if (!campaign) throw new CampaignEditorError(404, "Campanha não encontrada");
    assertEditable(campaign);
    const [editor] = await tx.select().from(campaignEditor).where(eq(campaignEditor.campaignId, campaignId));
    const packages = await tx.select().from(campaignPackages).where(eq(campaignPackages.campaignId, campaignId));
    const protectedIds = new Set<string>();
    for (const config of [...(editor ? [editor.config] : []), ...packages.map((p) => p.config)]) {
      for (const id of referencedAssetIds(config)) protectedIds.add(id);
    }
    const rows = await tx.select().from(campaignAssets).where(eq(campaignAssets.campaignId, campaignId));
    const objects = await listPrivateObjects(campaignAssetPrefix(campaignId));
    const byId = new Map(rows.map((row) => [row.id, row]));
    const stored = new Map(objects.flatMap((obj) => {
      const id = assetIdFromKey(campaignId, obj.key);
      // Only canonical keys generated by the server can be deleted.
      return id && obj.key === campaignAssetKey(campaignId, id) ? [[id, obj] as const] : [];
    }));
    const now = new Date();
    const eligible = (id: string) => {
      if (protectedIds.has(id)) return false;
      const row = byId.get(id), object = stored.get(id);
      if (!row && !object) return false;
      if (row && row.key !== campaignAssetKey(campaignId, id)) return false;
      return options.afterSave || ((!row || oldEnough(row.createdAt, now)) && (!object || oldEnough(object.lastModified, now)));
    };
    const candidates = [...new Set([...byId.keys(), ...stored.keys()])].filter(eligible).map((id) => ({ id, ...(stored.get(id)?.size !== undefined ? { bytes: stored.get(id)!.size } : {}) }));
    if (!options.ids) return { candidates, count: candidates.length, ...(candidates.every((item) => item.bytes !== undefined) ? { totalBytes: candidates.reduce((sum, item) => sum + (item.bytes ?? 0), 0) } : {}) };
    const result: CleanupResult = { deleted: [], failed: [], skipped: [], deletedBytes: 0 };
    for (const id of options.ids) {
      if (!eligible(id)) { result.skipped.push(id); continue; }
      try { await deletePrivateObject(campaignAssetKey(campaignId, id)); }
      catch { result.failed.push(id); continue; }
      // A database failure aborts the transaction; callers report warning and may retry.
      await tx.delete(campaignAssets).where(and(eq(campaignAssets.campaignId, campaignId), eq(campaignAssets.id, id)));
      result.deleted.push(id);
      result.deletedBytes += stored.get(id)?.size ?? 0;
    }
    return result;
  });
}
