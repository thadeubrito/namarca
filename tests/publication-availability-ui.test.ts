import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

test('publicação separa ações de conteúdo e acesso, com confirmação e sem ativação implícita', () => {
  const ui = readFileSync('apps/admin/src/components/admin-workspace/publication.tsx', 'utf8');
  assert.match(ui, /published \? 'Publicar alterações' : 'Publicar campanha'/);
  assert.match(ui, /A campanha permanece suspensa ao publicar alterações/);
  assert.doesNotMatch(ui, /<Notice>Acesso público suspenso/);
  assert.match(ui, /suspended \? 'Reativar campanha' : 'Suspender campanha'/);
  assert.doesNotMatch(ui, /window\.(confirm|alert|prompt)/);
  assert.match(ui, /<AlertDialog open=\{confirmation !== null\}/);
  assert.match(ui, /<AlertDialogCancel asChild>/);
  assert.match(ui, /event\.preventDefault\(\)/);
  assert.match(ui, /\{delivered && <form ref=\{accessForm\} hidden action=\{accessSubmit\}/);
  assert.match(ui, /disabled=\{working\}/);
  assert.match(ui, /Alterações não publicadas não serão incluídas/);
  const sections = readFileSync('apps/admin/src/components/admin-workspace/campaign-sections.tsx', 'utf8');
  assert.match(sections, /id: 'publicacao', label: 'Publicação'/);
  assert.doesNotMatch(sections, /Publicação · alterações|Publicação pendente/);
  assert.match(ui, /A campanha permanece suspensa/);
  assert.match(ui, /currentVersion = delivered \? version/);
  assert.match(ui, /nextVersion = published && delivered \? Math\.max\(version, \.\.\.versions\.map\(item => item\.version\)\) \+ 1 : version/);
  assert.match(ui, /displayedVersion = currentVersion \?\? version/);
  assert.doesNotMatch(ui, /displayedVersion = .*nextVersion/);
  assert.match(ui, /aria-label="Publicação atual"/);
  assert.match(ui, /<h2>\{currentVersion \? `Versão \$\{currentVersion\}` : 'Ainda não publicada'\}<\/h2>/);
  assert.match(ui, /currentVersion \? 'Publicada atualmente'/);
  assert.match(ui, /aria-label=\{pendingDelivery \? 'Envio pendente' : 'Próxima publicação'\}/);
  assert.match(ui, /As alterações salvas substituirão a Versão/);
  assert.match(ui, /Salve as alterações nas abas editadas para continuar/);
  assert.doesNotMatch(ui, /<Notice>Salve as alterações para publicar/);
  assert.doesNotMatch(ui, /Rascunho do administrativo|Se houver diferenças/);
  assert.ok(ui.indexOf('<PublicationDiff') < ui.indexOf('<PublicationVersions'), 'Comparison precedes historical maintenance');
  assert.doesNotMatch(ui, /ArrowRight|ws-publication-versions/);
  assert.doesNotMatch(ui, /Versão publicada: v/);
  const page = readFileSync('apps/admin/src/app/(workspace)/campanhas/[id]/page.tsx', 'utf8');
  const heading = page.slice(page.indexOf('<header className="ws-campaign-heading"'), page.indexOf('</header>'));
  assert.match(heading, /Alterações não publicadas/);
  assert.match(heading, /Envio pendente/);
  assert.doesNotMatch(heading, /Versão|versions\.|Atualizada/);
  assert.match(ui, /delivered && unpublishedChanges && <form ref=\{discardForm\} hidden action=\{discardSubmit\}/);
  assert.match(ui, /ref=\{discardButton\} variant="ghost" disabled=\{working \|\| anyDirty\}/);
  assert.match(ui, /ref=\{accessButton\} variant="secondary" disabled=\{working\}/);
  assert.doesNotMatch(ui, /DropdownMenu|optionsTrigger|Mais opções de publicação/);
  const live = ui.slice(ui.indexOf('<section className="ws-publication-live"'), ui.indexOf('<section className="ws-publication-draft"'));
  assert.match(live, /ref=\{accessButton\}/);
  assert.doesNotMatch(live, /ref=\{discardButton\}/);
  const draftPanel = ui.slice(ui.indexOf('<section className="ws-publication-draft"'), ui.indexOf('<PublicationDiff'));
  assert.match(draftPanel, /ref=\{publishButton\}/);
  assert.match(draftPanel, /ref=\{discardButton\}/);
  assert.match(ui, /setConfirmation\('discard'\)/);
  assert.match(ui, /setConfirmation\('access'\)/);
  assert.match(ui, /anyDirty \|\| !confirmed\.current/);
  assert.match(ui, /confirmed\.current = true/);
  assert.match(ui, /confirmationOrigin\.current === 'publish' \? publishButton : confirmationOrigin\.current === 'discard' \? discardButton : accessButton/);
  assert.match(ui, /discard\.restored\) window\.location\.reload\(\)/);
  assert.match(ui, /Cliente, observações, cobranças e disponibilidade não serão alterados/);
});
