// Generate runtime geometry from the authored stylesheet; no live CSSOM reads.
import { readFile, writeFile } from 'node:fs/promises';
const source=new URL('../apps/site/estudos/lima/materials.css',import.meta.url);
const target=new URL('../apps/site/estudos/lima/photo-geometry.js',import.meta.url);
const css=await readFile(source,'utf8');
const config=Array.from({length:5},(_,index)=>({
 geometry:['left','top','width','height'].map(key=>parseFloat(css.match(new RegExp(`--perspective-photo-${index}-${key}:([^;]+)`))[1])),
 points:[...css.match(new RegExp(`photo\\[data-shape='${index}'\\] img\\{[^}]*clip-path:([^}]+)`))[1].matchAll(/(-?[\d.]+)%\s+(-?[\d.]+)%/g)].map(m=>[Number(m[1]),Number(m[2])])
}));
const result=`/* Generated by scripts/prepare-lima-photo-geometry.mjs from materials.css. */\nwindow.namarcaHeroGeometry = ${JSON.stringify(config)};\n`;
if(process.argv.includes('--check')) {
 if(await readFile(target,'utf8')!==result)throw new Error('Regenerate hero geometry after changing materials.css');
}else await writeFile(target,result);
